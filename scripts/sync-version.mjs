/**
 * Single-source the version: package.json is the ONLY place the version
 * lives. This script stamps it into apps/cli/src/version.ts (the only
 * place the runtime can read it without fragile relative-path requires
 * after the dist/ tree is flattened/obfuscated).
 *
 * Runs automatically before every build (`npm run build`) and can be run
 * standalone: `npm run sync-version`.
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const PKG = path.join(ROOT, "package.json");
const OUT = path.join(ROOT, "apps", "cli", "src", "version.ts");

const pkg = JSON.parse(fs.readFileSync(PKG, "utf8"));
const version = String(pkg.version ?? "");
if (!/^\d+\.\d+\.\d+(-[0-9A-Za-z.-]+)?$/.test(version)) {
  console.error(`sync-version: package.json version "${version}" is not valid semver.`);
  process.exit(1);
}

const banner = `/* AUTO-GENERATED by scripts/sync-version.mjs — DO NOT EDIT BY HAND.
 * Source of truth: package.json "version".
 */
export const VERSION = "${version}"
`;
const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
if (current === banner) {
  console.log(`sync-version: version.ts already at ${version}.`);
} else {
  fs.writeFileSync(OUT, banner, "utf8");
  console.log(`sync-version: stamped ${version} into apps/cli/src/version.ts.`);
}
