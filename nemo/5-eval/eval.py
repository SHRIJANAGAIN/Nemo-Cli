#!/usr/bin/env python3
"""
Shrijan - Evaluation Engine
===============================
Reads MISTAKES.MD, IMPROVEMENT.MD, HISTORY.MD and the excluded-points
ledger to compute per-task reliability scores and a global reputation.

Reliability formula:
    reliability = improvements / (improvements + repeats)
    global_reliability = weighted average over the last 30 days
"""

from __future__ import annotations

import argparse
import datetime as _dt
import json
import os
import re
import sys
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple


WINDOW_DAYS = 30
TASK_RUBRIC = {
    "easy": 1,
    "normal": 2,
    "medium": 3,
    "high": 5,
    "critical": 8,
}


@dataclass
class EvalRow:
    timestamp: str
    task_id: str
    task_type: str
    score: float
    notes: str = ""


@dataclass
class EvalReport:
    generated: str
    reliability: float
    improvements: int
    repeats: int
    by_type: Dict[str, float]
    notes: List[str] = field(default_factory=list)


def _read_md_sections(path: Path) -> List[Tuple[str, str]]:
    """Split a Markdown file into (heading, body) tuples."""
    if not path.exists():
        return []
    out: List[Tuple[str, str]] = []
    current_heading = ""
    current_body: List[str] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("## "):
            if current_heading or current_body:
                out.append((current_heading, "\n".join(current_body).strip()))
            current_heading = line[3:].strip()
            current_body = []
        else:
            current_body.append(line)
    if current_heading or current_body:
        out.append((current_heading, "\n".join(current_body).strip()))
    return out


def _count_recent(path: Path, pattern: str, window_days: int = WINDOW_DAYS) -> int:
    if not path.exists():
        return 0
    cutoff = _dt.datetime.now(_dt.timezone.utc) - _dt.timedelta(days=window_days)
    rx = re.compile(pattern)
    count = 0
    for heading, _body in _read_md_sections(path):
        m = re.match(r"^(\d{4}-\d{2}-\d{2})", heading)
        if m:
            try:
                d = _dt.datetime.fromisoformat(heading.split("T")[0])
            except ValueError:
                continue
            if d < cutoff:
                continue
        if rx.search(heading):
            count += 1
    return count


def evaluate(root: str | os.PathLike[str] = ".") -> EvalReport:
    root = Path(root)
    err_dir = root / "nemo" / "1-errors"
    hist_md = root / "nemo" / "6-u" / "HISTORY.MD"
    improvements = _count_recent(err_dir / "IMPROVEMENT.MD", r".")
    repeats = _count_recent(err_dir / "2nd-mistake.md", r".")
    reliability = improvements / max(1, improvements + repeats)
    by_type: Dict[str, float] = {}
    for t, weight in TASK_RUBRIC.items():
        type_improvements = _count_recent(err_dir / "IMPROVEMENT.MD", t) if t else improvements
        type_repeats = _count_recent(err_dir / "2nd-mistake.md", t) if t else repeats
        by_type[t] = type_improvements / max(1, type_improvements + type_repeats) * weight
    notes: List[str] = []
    if reliability >= 0.8:
        notes.append("HIGH reliability — bonus +5 on high/critical tasks.")
    elif reliability < 0.5:
        notes.append("LOW reliability — restricted to easy tasks for 24h.")
    return EvalReport(
        generated=_dt.datetime.now(_dt.timezone.utc).isoformat(timespec="seconds"),
        reliability=round(reliability, 4),
        improvements=improvements,
        repeats=repeats,
        by_type={k: round(v, 4) for k, v in by_type.items()},
        notes=notes,
    )


def write_eval(root: str | os.PathLike[str], report: EvalReport) -> Path:
    out = Path(root) / "nemo" / "5-eval" / "EVALS.MD"
    out.parent.mkdir(parents=True, exist_ok=True)
    if not out.exists():
        out.write_text(
            "# Shrijan — Evaluation History\n\n"
            "Auto-regenerated by `5-eval/eval.py`. One row per evaluation cycle.\n\n",
            encoding="utf-8",
        )
    with out.open("a", encoding="utf-8", newline="\n") as fp:
        fp.write(f"\n## {report.generated}\n")
        fp.write(f"- reliability: **{report.reliability}**\n")
        fp.write(f"- improvements: {report.improvements} | repeats: {report.repeats}\n")
        fp.write(f"- by_type: {json.dumps(report.by_type, ensure_ascii=False)}\n")
        for note in report.notes:
            fp.write(f"- note: {note}\n")
    return out


def _cli() -> int:
    p = argparse.ArgumentParser(description="Nemo eval")
    p.add_argument("--root", default=".")
    p.add_argument("--json", action="store_true")
    args = p.parse_args()
    report = evaluate(args.root)
    write_eval(args.root, report)
    if args.json:
        print(json.dumps(asdict(report), ensure_ascii=False, indent=2))
    else:
        print(f"reliability={report.reliability} improvements={report.improvements} repeats={report.repeats}")
    return 0


if __name__ == "__main__":
    sys.exit(_cli())
