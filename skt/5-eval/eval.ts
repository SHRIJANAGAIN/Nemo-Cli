import * as fs from "fs"
import path from "path"

declare const __dirname: string
import { loadMistakes } from "../1-errors/mistake.js"

export interface EvalEntry {
  sessionId: string
  timestamp: string
  userInput: string
  assistantOutput: string
  mistakesFound: string[]
  improvements: string[]
  score: number
}

function findSktRoot(): string {
  const cwdPath = path.join(process.cwd(), "skt", "5-eval")
  if (fs.existsSync(cwdPath)) return path.join(process.cwd(), "skt", "5-eval")
  return __dirname
}

function evalFile(): string {
  return path.join(findSktRoot(), "evals.json")
}

function evalrFile(): string {
  return path.join(findSktRoot(), "EVALR.MD")
}

export function loadEvals(): EvalEntry[] {
  try {
    if (!fs.existsSync(evalFile())) return []
    return JSON.parse(fs.readFileSync(evalFile(), "utf8")) as EvalEntry[]
  } catch {
    return []
  }
}

export function saveEvals(entries: EvalEntry[]): void {
  const dir = findSktRoot()
  fs.mkdirSync(dir, { recursive: true })
  fs.writeFileSync(evalFile(), JSON.stringify(entries, null, 2), "utf8")
}

export function checkForRepeatedMistakes(): string[] {
  const mistakes: any[] = loadMistakes()
  return mistakes.filter((m) => !m.isFixed && m.status !== "fixed").map((m) => m.errorName || m.title || "unknown")
}

export function loadEvalrTemplate(): string {
  try {
    if (!fs.existsSync(evalrFile())) return ""
    return fs.readFileSync(evalrFile(), "utf8")
  } catch {
    return ""
  }
}

export interface EvalrSummary {
  sessionId: string
  timestamp: string
  whatIsMistake: string
  whyAssistantDidIt: string
  reasonItHeld: string
  isUserMistake: boolean
  isAssistantMistake: boolean
  isDeviceError: boolean
  howToResolve: string
  isFixed: boolean
  whyFailed: string
  futurePrevention: string
}

export function runForcedEvalr(
  sessionId: string,
  mistakeDetail: {
    errorName: string
    errorDescription: string
    errorParagraph: string
    assistantOutput: string
    userInput: string
    whyAssistantDidIt?: string
    reasonItHeld?: string
    isUserMistake?: boolean
    isAssistantMistake?: boolean
    isDeviceError?: boolean
    howToResolve?: string
    isFixed?: boolean
    whyFailed?: string
    futurePrevention?: string
  },
): EvalrSummary {
  const summary: EvalrSummary = {
    sessionId,
    timestamp: new Date().toISOString(),
    whatIsMistake: `${mistakeDetail.errorName}: ${mistakeDetail.errorDescription}`,
    whyAssistantDidIt: mistakeDetail.whyAssistantDidIt || "N/A",
    reasonItHeld: mistakeDetail.reasonItHeld || "N/A",
    isUserMistake: mistakeDetail.isUserMistake || false,
    isAssistantMistake: mistakeDetail.isAssistantMistake || false,
    isDeviceError: mistakeDetail.isDeviceError || false,
    howToResolve: mistakeDetail.howToResolve || "N/A",
    isFixed: mistakeDetail.isFixed || false,
    whyFailed: mistakeDetail.whyFailed || "",
    futurePrevention: mistakeDetail.futurePrevention || "",
  }

  const dir = findSktRoot()
  fs.mkdirSync(dir, { recursive: true })
  const reportPath = path.join(dir, `evalr-${sessionId}.md`)
  const reportContent = [
    "# EVALR - Mistake Evaluation Summary",
    "",
    `## Session: ${sessionId}`,
    `## Timestamp: ${summary.timestamp}`,
    "",
    "### 1. What is the mistake?",
    `- ${summary.whatIsMistake}`,
    "",
    "### 2. Why did I make this mistake?",
    `- whyAssistantDidIt: ${summary.whyAssistantDidIt}`,
    `- reasonItHeld: ${summary.reasonItHeld}`,
    "",
    "### 3. If I was in the place of user, what would happen?",
    `- isUserMistake: ${summary.isUserMistake}`,
    `- isAssistantMistake: ${summary.isAssistantMistake}`,
    `- isDeviceError: ${summary.isDeviceError}`,
    "",
    "### 4. How can I fix this mistake?",
    `- ${summary.howToResolve}`,
    "",
    "### 5. Did I fix the mistake?",
    `- isFixed: ${summary.isFixed}`,
    summary.isFixed ? "" : "### 6. If not fixed, why did I fail to fix it?\n- " + summary.whyFailed,
    summary.futurePrevention ? "### Future Prevention:\n- " + summary.futurePrevention : "",
    "",
    "---",
    "*Generated by EVALR.MD forced evaluation system.*",
  ].join("\n")

  fs.writeFileSync(reportPath, reportContent, "utf8")
  return summary
}

export function runEval(sessionId: string, userInput: string, assistantOutput: string): EvalEntry {
  const mistakes = checkForRepeatedMistakes()
  const prevEvals = loadEvals()
  const recentMistakes = prevEvals.filter((e) => e.mistakesFound.length > 0).slice(-5)

  let score = 100
  score -= mistakes.length * 10
  score -= recentMistakes.length * 5
  score = Math.max(0, Math.min(100, score))

  const entry: EvalEntry = {
    sessionId,
    timestamp: new Date().toISOString(),
    userInput: userInput.slice(0, 500),
    assistantOutput: assistantOutput.slice(0, 1000),
    mistakesFound: mistakes,
    improvements: [],
    score,
  }

  prevEvals.push(entry)
  saveEvals(prevEvals)
  return entry
}

export function getEvalReport(): string {
  const evals = loadEvals()
  if (evals.length === 0) return "No evaluations yet."
  const avgScore = Math.round(evals.reduce((s, e) => s + e.score, 0) / evals.length)
  const last = evals[evals.length - 1]
  return [
    `TRAYAMBAK EVAL REPORT`,
    `Sessions Evaluated: ${evals.length}`,
    `Average Score: ${avgScore}/100`,
    `Last Score: ${last.score}/100`,
    `Open Mistakes: ${last.mistakesFound.length}`,
  ].join("\n")
}
